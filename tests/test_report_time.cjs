'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require.resolve('../app/app.js'),'utf8');
const {reportTime,reportOrder}=vm.runInNewContext(source.slice(source.indexOf('function reportTime('),source.indexOf('function reportRows('))+';({reportTime,reportOrder})');
const midnight=reportTime('Mon Sep 28 12:24:59 AM UTC 2026');
assert.equal(midnight.date,'2026-09-28');
assert.equal(midnight.clock,'00:24:59');
assert.equal(midnight.zone,'UTC');
assert.equal(midnight.stamp,Date.parse('2026-09-28T00:24:59Z'));
assert.equal(reportTime('Mon Sep 28 12:24:59 PM UTC 2026').clock,'12:24:59');
assert.equal(reportTime('Sat Oct 10 08:43:58 AM UTC 2026').stamp,Date.parse('2026-10-10T08:43:58Z'));
assert.equal(reportTime('2026-10-10T16:43:58+08:00').stamp,Date.parse('2026-10-10T08:43:58Z'));
assert.equal(reportTime('unknown timestamp').raw,'unknown timestamp');
assert.ok(Number.isNaN(reportTime('').stamp));
const old={server:{time:'Mon Sep 28 12:24:59 AM UTC 2026'}},recent={server:{time:'Sat Oct 10 08:43:58 AM UTC 2026'}},unknown={server:{time:''}};
assert.ok(reportOrder(old,recent)<0);
assert.ok(reportOrder(old,recent,true)>0);
assert.ok(reportOrder(unknown,recent)>0);
assert.ok(reportOrder(unknown,recent,true)>0);
console.log('Report collection time display and ordering checks passed');
